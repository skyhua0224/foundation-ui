// Builds src/search/pinyinTable.js: the toneless pinyin of the Han characters that the products' texts use, so that the search finds 音频 by `yinpin`.
// Source: the Unicode Character Database, Unihan_Readings.txt (kMandarin: the reading in use today; kHanyuPinyin: every reading, for the few characters
// below that are read two ways in the settings words). Only characters that occur in the texts given with --text are kept, which keeps the table small.
//
//   node --import ./scripts/register.mjs scripts/gen-pinyin.mjs --unihan Unihan_Readings.txt [--text <file-or-dir> ...] [--out src/search/pinyinTable.js]
//
// The characters are those of what the search can find: the words of this package (the synonym table, the actions, the tiles of the overview, the settings pages) and the text
// files given with --text, which a product writes from its own search docs (the titles, places, keywords and aliases of its settings and pages).

// A character the table lacks still works (its initial comes from the browser's own collation); the tests of each product check that its own texts are covered.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const args = process.argv.slice(2)
const take = (name) => { const out = []; args.forEach((a, i) => { if (a === name) out.push(args[i + 1]) }); return out }
const unihan = take('--unihan')[0]
const texts = take('--text')
const out = take('--out')[0] || new URL('../src/search/pinyinTable.js', import.meta.url).pathname
if (!unihan) { console.error('usage: gen-pinyin.mjs --unihan <Unihan_Readings.txt> [--text <file|dir> ...] [--out file]'); process.exit(2) }

// characters read two ways in the words of the settings (行 xing/hang, 重 zhong/chong ...): the second reading is added to the table
const POLYPHONES = Array.from('重行长传调会乐参数校觉少曲降便着差度率地给假角解处切还为发的了得都只与和载间种模没号干量应藏铺薄冲看更相调').filter((c, i, a) => a.indexOf(c) === i)

const TONES = { ā: 'a', á: 'a', ǎ: 'a', à: 'a', ē: 'e', é: 'e', ě: 'e', è: 'e', ī: 'i', í: 'i', ǐ: 'i', ì: 'i', ō: 'o', ó: 'o', ǒ: 'o', ò: 'o', ū: 'u', ú: 'u', ǔ: 'u', ù: 'u', ǖ: 'u', ǘ: 'u', ǚ: 'u', ǜ: 'u', ü: 'u', ń: 'n', ň: 'n', ǹ: 'n', ḿ: 'm' }
const plain = (s) => Array.from(s.normalize('NFC')).map((c) => TONES[c] || c).join('')

const walk = (p) => (statSync(p).isDirectory() ? readdirSync(p).filter((n) => n !== 'node_modules' && !n.startsWith('.')).flatMap((n) => walk(join(p, n))) : [p])
const used = new Set()
for (const t of texts) for (const f of walk(t)) if (/\.(js|mjs|vue|json|md|txt)$/.test(f) && !f.endsWith('pinyinTable.js')) for (const ch of readFileSync(f, 'utf8')) if (ch >= '一' && ch <= '鿿') used.add(ch)

// the package's own words
const { SYNONYM_GROUPS } = await import('../src/search/synonyms.js')
const { searchTexts, altActionTexts } = await import('../src/search/texts.js')
const { tileDocs } = await import('../src/search/docs.js')
const { SETTINGS_CATEGORIES } = await import('../src/settings/model.js')
const own = [JSON.stringify(SYNONYM_GROUPS), JSON.stringify(searchTexts('zh')), JSON.stringify(altActionTexts('en')), JSON.stringify(tileDocs('zh')), JSON.stringify(SETTINGS_CATEGORIES)].join('\n')
for (const ch of own) if (ch >= '一' && ch <= '鿿') used.add(ch)

const mandarin = new Map(), all = new Map()
for (const line of readFileSync(unihan, 'utf8').split('\n')) {
  const [cp, field, value] = line.split('\t')
  if (!value || (field !== 'kMandarin' && field !== 'kHanyuPinyin')) continue
  const ch = String.fromCodePoint(parseInt(cp.slice(2), 16))
  if (!used.has(ch)) continue
  if (field === 'kMandarin') mandarin.set(ch, value.split(' ').map(plain))
  else all.set(ch, value.split(' ').flatMap((v) => v.slice(v.indexOf(':') + 1).split(',')).map(plain))
}
const main = new Map(), alt = new Map()
const missing = []
for (const ch of used) {
  const m = mandarin.get(ch) || all.get(ch)
  if (!m) { missing.push(ch); continue }
  main.set(ch, m[0])
  const extra = new Set([...(m.slice(1)), ...(POLYPHONES.includes(ch) ? all.get(ch) || [] : [])])
  extra.delete(m[0])
  if (extra.size && POLYPHONES.includes(ch)) alt.set(ch, [...extra].slice(0, 3))
}
const group = (entries) => { const by = new Map(); for (const [ch, s] of entries) by.set(s, (by.get(s) || '') + ch); return [...by].sort(([a], [b]) => (a < b ? -1 : 1)).map(([s, cs]) => `${s}:${cs}`).join(';') }
const altEntries = []; for (const [ch, list] of alt) for (const s of list) altEntries.push([ch, s])
const file = `// Generated by scripts/gen-pinyin.mjs from the Unicode Character Database (Unihan_Readings.txt; Copyright © 1991-2026 Unicode, Inc., Unicode License v3, see LICENSES/Unicode-3.0.txt; Unicode ${/Unicode Version (\S+)/.exec(readFileSync(unihan, 'utf8').slice(0, 2000))?.[1] || 'unknown'}): the toneless pinyin of ${main.size} characters of the products' texts.\n// Do not edit by hand; run the script again when a text gains a character the table lacks.\n// "syllable:characters;..." -- MAIN is the reading in use, ALT the other readings of the characters that are read two ways in the settings words.\nexport const PINYIN_MAIN = '${group(main)}'\nexport const PINYIN_ALT = '${group(altEntries)}'\n`
writeFileSync(out, file)
console.log(`${main.size} characters, ${alt.size} with a second reading, ${missing.length} without a reading${missing.length ? `: ${missing.join('')}` : ''}; ${file.length} bytes`)
