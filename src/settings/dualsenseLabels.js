const isChinese = (locale) => String(locale || "").startsWith("zh")

export function localizedKeyLabel(descriptor, locale) {
  const names = isChinese(locale) ? zhKeyLabels : enKeyLabels
  return names[descriptor.key] || descriptor.label
}

export function localizedOptionLabel(option, locale) {
  const names = isChinese(locale) ? zhOptionLabels : enOptionLabels
  return names[option] || option
}
