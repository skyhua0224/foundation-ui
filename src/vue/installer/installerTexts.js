/** zh for any Chinese tag (zh, zh-CN, zh-TW), en for every other language: the installer has only these two */
export const localeOf = (tag) => (/^zh\b/i.test(String(tag || '')) ? 'zh' : 'en')

/** t('zh', 'welcome.title') or t('zh', 'maint.lead', 'a', 'b') for a string that takes values; an unknown key throws (a missing word must show in a test, not on a screen) */
export function t(locale, key, ...args) {
  const table = TEXT[locale] || TEXT[localeOf(locale)]
  const v = table[key]
  if (v === undefined) throw new Error(`installer text missing: ${locale}.${key}`)
  return typeof v === 'function' ? v(...args) : v
}

/** every key of one locale (the tests compare zh and en) */
export function textKeys(locale) { return Object.keys(TEXT[locale]) }
